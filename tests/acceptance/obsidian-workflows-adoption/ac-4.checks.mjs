// Increment: [[docs/increments/obsidian-workflows-adoption]]
// AC-4: Projects generated with `azure-devops` or `none` hosting contain neither `.github/workflows/obsidian-release.yml` nor the action reference, and switching an existing project to `github` with `node bin/app hosting set github` plans `obsidian-release.yml` without overwriting an existing file.
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { compileProject, loadTemplateSnapshot } from '../../../src/cli/compiler/index.ts';
import { executeOperation } from '../../../src/cli/adapters/framework/operations.ts';
import { parseCliArguments } from '../../../src/cli/adapters/framework/catalog.ts';
import { starterDocument, starterDocumentText } from '../../../src/shared/testing/starter-documents.mjs';
import { withHostingOption } from '../../../src/shared/companion/tooling-options.ts';

const frameworkRoot = await realpath(resolve(import.meta.dirname, '../../..'));
const template = await loadTemplateSnapshot(frameworkRoot);
const release = '.github/workflows/obsidian-release.yml';
async function artifacts(document) {
  const result = await compileProject({ source: JSON.stringify(document), template });
  assert.equal(result.status, 'ok', JSON.stringify(result.diagnostics));
  return result.artifacts;
}
const run = (context, argv) => executeOperation(parseCliArguments(argv), context);

test('[AC-4] Azure DevOps and none projects get no Obsidian release workflow and no reference to the action', async () => {
  const azure = { hosting: 'azure-devops', azureOrganization: 'https://dev.azure.com/contoso', azureProject: 'Quick Capture', azureRepository: 'quick-capture' };
  for (const options of [azure, { hosting: 'none' }]) {
    const files = await artifacts(withHostingOption(starterDocument('quick-capture'), options));
    assert.ok(!files.some(file => file.path.startsWith('.github/')), options.hosting);
    // The project's own CI and guidance; the framework's templates and tests travel along only as inert reference.
    const own = files.filter(file => /^(?:azure-pipelines\.yml|README\.md|AGENTS\.md|\.azuredevops\/.+|docs\/project-tasks\/.+)$/.test(file.path));
    assert.ok(own.some(file => file.path === 'README.md'), options.hosting);
    const referencing = own.filter(file => /obsidianmd\/obsidian-workflows|obsidian-release\.yml/.test(file.content)).map(file => file.path);
    assert.deepEqual(referencing, [], options.hosting);
  }
});

test('[AC-4] hosting set github creates obsidian-release.yml as generated and keeps an existing one', async t => {
  const root = await realpath(await mkdtemp(join(tmpdir(), 'obsidian-release-hosting-')));
  t.after(() => rm(root, { recursive: true, force: true }));
  const context = { root, frameworkRoot };
  await writeFile(join(root, 'input.json'), starterDocumentText('quick-capture'));
  assert.equal((await run(context, ['setup', '--input', 'input.json', '--yes'])).status, 'applied');
  assert.equal((await run(context, ['hosting', 'set', 'none', '--yes'])).status, 'applied');
  const generated = (await artifacts(starterDocument('quick-capture'))).find(file => file.path === release);
  const preview = await run(context, ['hosting', 'set', 'github', '--dry-run']);
  assert.equal(preview.status, 'planned', JSON.stringify(preview.diagnostics));
  const created = preview.data.changes.find(change => change.path === release);
  assert.equal(created?.status, 'create');
  const applied = await run(context, ['hosting', 'set', 'github', '--apply', preview.data.planHash]);
  assert.equal(applied.status, 'applied', JSON.stringify(applied.diagnostics));
  assert.equal(await readFile(join(root, release), 'utf8'), generated.content, 'hosting set writes the generated bytes');

  await run(context, ['hosting', 'set', 'none', '--yes']);
  await mkdir(join(root, '.github/workflows'), { recursive: true });
  await writeFile(join(root, release), 'name: Team release\n');
  const again = await run(context, ['hosting', 'set', 'github', '--dry-run']);
  assert.equal(again.status, 'planned', JSON.stringify(again.diagnostics));
  assert.ok(!again.data.changes.some(change => change.path === release), 'an existing release workflow is never replaced');
  assert.equal(await readFile(join(root, release), 'utf8'), 'name: Team release\n');
});
