import assert from 'node:assert/strict';
const { test } = await (process.env.VITEST ? import('vitest') : import('node:test'));
import { parseFrontmatter as dorFrontmatter } from '../../scripts/delivery/handoff.mjs';
import { createWorkspace, planThenApply, readyFragment } from '../support/increment-workspace.mjs';

const fails = (outcome, code) => { assert.equal(outcome.status, 'failed', JSON.stringify(outcome)); assert.equal(outcome.diagnostics[0].code, code, outcome.diagnostics[0].message); };
async function inWorkspace(options, body) {
  const ws = createWorkspace(options);
  try { await body(ws); } finally { ws.remove(); }
}
const newIncrement = (ws, options = {}) => planThenApply(ws, 'increment new', ['delivery'], { title: 'Delivery pipeline', owner: 'Luis', ...options });

test('increment new previews without writing, then creates the increment, kick-off pull request, issue and branch in one reviewed plan', () => inWorkspace({ delivery: true }, async ws => {
  const options = { title: 'Delivery pipeline', owner: 'Luis' };
  const preview = await ws.run('increment new', ['delivery'], options);
  assert.equal(preview.status, 'planned', JSON.stringify(preview.diagnostics));
  assert.equal(ws.exists('docs'), false); assert.deepEqual(ws.branches(), ['main']);
  assert.deepEqual(preview.data.changes.map(change => [change.path, change.status]), [
    ['docs/increments/delivery.md', 'create'], ['docs/pull-requests/delivery-kickoff.md', 'create'], ['docs/issues/delivery.md', 'create']]);
  assert.deepEqual(preview.data.steps, [{ kind: 'git-branch', name: 'increment/delivery', start: 'main', commit: ws.git('rev-parse', 'main'), switch: false, fetch: null }]);
  assert.deepEqual(preview.data.summary.created, { increment: 'docs/increments/delivery.md', pullRequest: 'docs/pull-requests/delivery-kickoff.md', issue: 'docs/issues/delivery.md', stubs: [] });
  assert.equal((await ws.run('increment new', ['delivery'], options)).data.planHash, preview.data.planHash, 'the same inputs plan the same hash');
  const applied = await ws.run('increment new', ['delivery'], { ...options, apply: preview.data.planHash });
  assert.equal(applied.status, 'applied'); assert.equal(applied.data.applied.written.length, 3);
  assert.deepEqual(applied.data.applied.steps, { name: 'increment/delivery', status: 'created', start: 'main' });
  assert.deepEqual(ws.branches(), ['increment/delivery', 'main']); assert.equal(ws.git('rev-parse', '--abbrev-ref', 'HEAD'), 'main');
  const increment = ws.read('docs/increments/delivery.md');
  assert.match(increment, /^pullRequests: \[delivery-kickoff\]\nissues: \[delivery\]\nbranch: "increment\/delivery"\nbase: main\n---/m);
  assert.match(increment, /<!-- wb:pull-requests generated by node bin\/app; edits here are replaced -->\n- \[\[docs\/pull-requests\/delivery-kickoff\|Kick-off: Delivery pipeline\]\] · New\n/);
  assert.match(increment, /- \[\[docs\/issues\/delivery\|Delivery pipeline\]\] · New\n/);
  assert.deepEqual(dorFrontmatter(increment.split('\n')).errors, [], 'the Definition of Ready parser reads the written frontmatter');
  assert.match(ws.read('docs/pull-requests/delivery-kickoff.md'), /^kind: kickoff\nincrement: delivery\nstatus: New\nhead: "increment\/delivery"\nbase: main\n/m);
  assert.match(ws.read('docs/issues/delivery.md'), /^status: New\nincrement: delivery\n---/m);
  fails(await ws.run('increment new', ['delivery'], options), 'INCREMENT_EXISTS');
}));

test('the plan hash binds the branch start commit: a new commit on main makes the reviewed plan stale', () => inWorkspace({ delivery: true }, async ws => {
  const preview = await ws.run('increment new', ['delivery'], { title: 'Delivery pipeline' });
  ws.write('CHANGE.md', 'moved\n'); ws.git('add', '-A'); ws.git('commit', '-q', '-m', 'move main');
  fails(await ws.run('increment new', ['delivery'], { title: 'Delivery pipeline', apply: preview.data.planHash }), 'PLAN_STALE');
  assert.equal(ws.exists('docs/increments/delivery.md'), false); assert.deepEqual(ws.branches(), ['main']);
}));

test('--no-issue and --no-branch leave them out; an existing branch is kept and --switch checks a new one out', () => inWorkspace({ delivery: true }, async ws => {
  const skipped = await newIncrement(ws, { 'no-issue': true, 'no-branch': true });
  assert.equal(skipped.status, 'applied'); assert.equal(ws.exists('docs/issues/delivery.md'), false); assert.deepEqual(ws.branches(), ['main']);
  assert.equal(skipped.data.summary.branch.status, 'skipped'); assert.equal(skipped.data.steps, undefined);
  ws.git('branch', 'increment/second');
  const kept = await planThenApply(ws, 'increment new', ['second'], { title: 'Second' });
  assert.equal(kept.data.summary.branch.status, 'exists');
  const switched = await planThenApply(ws, 'increment new', ['third'], { title: 'Third', switch: true });
  assert.equal(switched.data.applied.steps.status, 'created-and-switched'); assert.equal(ws.git('rev-parse', '--abbrev-ref', 'HEAD'), 'increment/third');
  fails(await ws.run('increment new', ['fourth'], { title: 'Fourth', switch: true, 'no-branch': true }), 'INVALID_OPTION');
  fails(await ws.run('increment new', ['fourth'], { title: 'Fourth', branch: true, 'no-branch': true }), 'INVALID_OPTION');
}));

