test('write commands refuse a delivery.json pointing at other folders (DELIVERY_PATHS_DRIFT); read commands report it', () => inWorkspace({ delivery: true }, async ws => {
  await newIncrement(ws, { 'no-branch': true });
  const config = JSON.parse(ws.read('configs/delivery/delivery.json'));
  config.handoff.glob = 'docs/handoffs/*.md';
  ws.write('configs/delivery/delivery.json', JSON.stringify(config));
  fails(await ws.run('increment scope add', ['delivery', 'More']), 'DELIVERY_PATHS_DRIFT');
  const listed = await ws.run('increment list');
  assert.equal(listed.status, 'ok'); assert.equal(listed.data.drift[0].code, 'DELIVERY_PATHS_DRIFT');
  const validated = await ws.run('increment validate');
  assert.equal(validated.status, 'blocked'); assert.equal(validated.diagnostics[0].code, 'DELIVERY_PATHS_DRIFT');
}));
