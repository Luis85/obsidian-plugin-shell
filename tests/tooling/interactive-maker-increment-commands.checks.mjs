test('criteria from --input get pending acceptance stubs and default evidence in the same plan; existing stubs are kept', () => inWorkspace({ delivery: true }, async ws => {
  ws.write('handoff.md', readyFragment);
  ws.write('tests/acceptance/delivery/ac-2.checks.mjs', '// already written\n');
  ws.write('tests/acceptance/delivery/ac-9.checks.mjs', '// orphan\n');
  const created = await newIncrement(ws, { input: 'handoff.md' });
  assert.equal(created.status, 'applied', JSON.stringify(created.diagnostics));
  assert.deepEqual(created.data.summary.stubs.created, ['tests/acceptance/delivery/ac-1.checks.mjs']);
  assert.deepEqual(created.data.summary.stubs.existing, ['tests/acceptance/delivery/ac-2.checks.mjs']);
  assert.deepEqual(created.data.summary.stubs.orphans, ['tests/acceptance/delivery/ac-9.checks.mjs']);
  assert.ok(created.data.summary.warnings.some(warning => warning.code === 'ACCEPTANCE_STUB_ORPHAN'));
  const stub = ws.read('tests/acceptance/delivery/ac-1.checks.mjs');
  assert.match(stub, /test\.todo\('delivery AC-1: Given a planned pull request When it is published Then a draft exists'\)/);
  assert.match(stub, /\[\[docs\/increments\/delivery\]\]/); assert.match(stub, /\/\/ Then a draft exists/);
  assert.equal(ws.read('tests/acceptance/delivery/ac-2.checks.mjs'), '// already written\n', 'an existing stub is never overwritten');
  assert.match(ws.read('docs/increments/delivery.md'), /- \[ \] AC-1: Given a planned pull request When it is published Then a draft exists\n {2}Evidence: `tests\/acceptance\/delivery\/ac-1\.checks\.mjs`\n/);
}));

test('increment edit, scope, ac add, ac set and ref add plan exact span edits; a new criterion brings its stub', () => inWorkspace({ delivery: true }, async ws => {
  await newIncrement(ws, { 'no-branch': true });
  const before = ws.read('docs/increments/delivery.md');
  const edited = await planThenApply(ws, 'increment edit', ['delivery'], { size: 'L', title: 'Delivery pipeline v2' });
  assert.equal(edited.status, 'applied'); assert.deepEqual(edited.data.applied.written, ['docs/increments/delivery.md']);
  const after = ws.read('docs/increments/delivery.md');
  assert.equal(after, before.replace('title: "Delivery pipeline"', 'title: "Delivery pipeline v2"').replace('size: M', 'size: L').replace('# Delivery pipeline\n', '# Delivery pipeline v2\n'));
  ws.write('summary.md', 'A new summary paragraph.\n');
  await planThenApply(ws, 'increment edit', ['delivery'], { section: 'Summary', input: 'summary.md' });
  assert.match(ws.read('docs/increments/delivery.md'), /## Summary\n\nA new summary paragraph\.\n\n## Outcome/);
  await planThenApply(ws, 'increment scope add', ['delivery', 'The publish command']);
  await planThenApply(ws, 'increment out-of-scope add', ['delivery', 'Merging']);
  const scope = ws.read('docs/increments/delivery.md');
  assert.match(scope, /### In scope\n\n- The publish command\n\n### Out of scope\n\n- Merging\n/, 'a new item replaces the template placeholder');
  const added = await planThenApply(ws, 'increment ac add', ['delivery', 'Publishing twice adopts the existing draft']);
  assert.equal(added.status, 'applied'); assert.deepEqual(added.data.summary.stubs.created, ['tests/acceptance/delivery/ac-1.checks.mjs']);
  assert.ok(ws.exists('tests/acceptance/delivery/ac-1.checks.mjs'));
  await planThenApply(ws, 'increment ac set', ['delivery', 'AC-1'], { status: 'done', evidence: 'README.md' });
  assert.match(ws.read('docs/increments/delivery.md'), /- \[x\] AC-1: Publishing twice adopts the existing draft\n {2}Evidence: `README\.md`\n/);
  fails(await ws.run('increment ac set', ['delivery', 'AC-1'], {}), 'INCREMENT_INPUT_INVALID');
  fails(await ws.run('increment ac set', ['delivery', 'AC-7'], { status: 'done' }), 'INCREMENT_AC_NOT_FOUND');
  fails(await ws.run('increment ac set', ['delivery', 'AC-1'], { status: 'finished' }), 'INVALID_OPTION');
  await planThenApply(ws, 'increment ref add', ['delivery', '[[README]]']);
  assert.match(ws.read('docs/increments/delivery.md'), /^refs: \["\[\[README\]\]"\]$/m);
  fails(await ws.run('increment ref add', ['delivery', '[[docs/missing]]']), 'WIKILINK_UNRESOLVED');
  fails(await ws.run('increment ref add', ['delivery', '[[README]]']), 'INCREMENT_UNCHANGED');
  fails(await ws.run('increment edit', ['delivery'], {}), 'INCREMENT_INPUT_INVALID');
  fails(await ws.run('increment edit', ['missing'], { size: 'S' }), 'INCREMENT_NOT_FOUND');
}));

test('status transitions: Ready runs the Definition of Ready, refused moves name the allowed ones, Cancelled locks edits', () => inWorkspace({ delivery: true }, async ws => {
  await newIncrement(ws, { 'no-branch': true });
  const notReady = await ws.run('increment status', ['delivery', 'Ready']);
  fails(notReady, 'INCREMENT_NOT_READY'); assert.match(notReady.diagnostics[0].message, /DOR-0\d/);
  fails(await ws.run('increment status', ['delivery', 'Done']), 'INCREMENT_STATUS_TRANSITION');
  fails(await ws.run('increment status', ['delivery', 'Shipped']), 'INCREMENT_STATUS_TRANSITION');
  const refining = await planThenApply(ws, 'increment status', ['delivery', 'refining']);
  assert.deepEqual([refining.data.summary.statusBefore, refining.data.summary.statusAfter], ['New', 'Refining']);
  await planThenApply(ws, 'increment status', ['delivery', 'Cancelled']);
  fails(await ws.run('increment scope add', ['delivery', 'More']), 'INCREMENT_LOCKED');
  fails(await ws.run('pr new', ['delivery'], { title: 'Late' }), 'INCREMENT_LOCKED');
  assert.equal((await planThenApply(ws, 'increment status', ['delivery', 'Refining'])).status, 'applied', 'Cancelled reopens to Refining');
}));

