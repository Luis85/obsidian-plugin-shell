test('attach moves a New pull request to another increment and updates both lists', () => inWorkspace({ delivery: true }, async ws => {
  await newIncrement(ws, { 'no-branch': true });
  await planThenApply(ws, 'increment new', ['other'], { title: 'Other', 'no-branch': true });
  await planThenApply(ws, 'pr new', ['delivery'], { title: 'Hosting set', 'no-branch': true });
  const moved = await planThenApply(ws, 'increment attach', ['other', 'delivery-1']);
  assert.equal(moved.status, 'applied'); assert.deepEqual(moved.data.summary.moved, { pullRequest: 'delivery-1', from: 'delivery', to: 'other' });
  assert.match(ws.read('docs/increments/delivery.md'), /^pullRequests: \[delivery-kickoff\]$/m);
  assert.match(ws.read('docs/increments/other.md'), /^pullRequests: \[other-kickoff, delivery-1\]$/m);
  const pull = ws.read('docs/pull-requests/delivery-1.md');
  assert.match(pull, /^increment: other$/m); assert.match(pull, /- \[\[docs\/increments\/other\|Increment: Other\]\]/); assert.doesNotMatch(pull, /docs\/increments\/delivery\|/);
  fails(await ws.run('increment attach', ['other', 'delivery-1']), 'INCREMENT_UNCHANGED');
  const valid = await ws.run('increment validate');
  assert.equal(valid.data.drift.length, 0); assert.ok(!valid.data.documents.some(doc => doc.problems.some(problem => problem.code === 'INCREMENT_LINK_DRIFT')));
}));

