/**
 * Pending acceptance test stubs of an Increment, planned with its documents: one file per criterion at the
 * configured pattern, never overwritten, and an empty `Evidence:` set to the stub. Rendering uses
 * `scripts/delivery/acceptance-stubs.mjs` `renderStub` with the configured template when both exist; otherwise a
 * built-in renderer producing the same pending `test.todo` stub. Criteria still holding template placeholders get
 * no stub until they are written.
 */
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { exists } from '../framework/files.ts';
import { acceptanceStubPath } from '../../domain/increments/model.ts';
import { editIncrement, parseIncrement } from '../../domain/increments/increment-document.ts';
import { hasPlaceholder } from '../../domain/increments/sections.ts';
import type { Session } from './session.ts';

interface Criterion { id: string; text: string }
interface StubContext { incrementId: string; incrementPath: string; criterion: Criterion }
type Render = (context: StubContext) => string;
export interface StubReport { renderer: 'acceptance-stubs.mjs' | 'built-in'; created: string[]; existing: string[]; orphans: string[] }

const comment = (text: string) => text.replace(/\s+/g, ' ').replace(/\*\//g, '* /').trim();
const quoted = (text: string) => text.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
function steps(text: string): string[] {
  const parts = text.split(/\b(?=(?:Given|When|Then|And)\b)/).map(part => part.trim().replace(/[,;]$/, '')).filter(Boolean);
  const gherkin = parts.some(part => part.startsWith('Given')) && parts.some(part => part.startsWith('Then'));
  return gherkin ? parts.filter(part => /^(?:Given|When|Then|And)\b/.test(part)).map(part => `// ${part}`) : [];
}
/** The built-in stub, equivalent to configs/delivery/acceptance-stub.checks.mjs.tmpl. */
export const builtInStub: Render = ({ incrementId, incrementPath, criterion }) => [
  `// ${incrementId} ${criterion.id}: acceptance test stub generated by \`node bin/app increment\`.`,
  '// Replace the pending test with assertions that prove the criterion; this file then is its Evidence.',
  `// Increment: [[${incrementPath.replace(/\.md$/, '')}]]`,
  `// ${criterion.id}: ${comment(criterion.text)}`,
  ...steps(criterion.text),
  "import test from 'node:test';",
  '',
  `test.todo('${incrementId} ${criterion.id}: ${quoted(comment(criterion.text))}');`,
  '',
].join('\n');

/** The configured renderer when scripts/delivery/acceptance-stubs.mjs and its template exist. */
async function renderer(session: Session): Promise<{ render: Render; name: StubReport['renderer'] }> {
  const root = session.ws.context.frameworkRoot, module = join(root, 'scripts/delivery/acceptance-stubs.mjs');
  const raw = await session.ws.read('configs/delivery/delivery.json');
  const parsed: unknown = raw ? JSON.parse(raw) : null;
  const acceptance: unknown = parsed && typeof parsed === 'object' && 'acceptance' in parsed ? parsed.acceptance : null;
  const template: unknown = acceptance && typeof acceptance === 'object' && 'template' in acceptance ? acceptance.template : null;
  const templateText = typeof template === 'string' ? await session.ws.read(template) : null;
  if (templateText === null || !await exists(module)) return { render: builtInStub, name: 'built-in' };
  const loaded: { renderStub?: unknown } = await import(pathToFileURL(module).href);
  const render = loaded.renderStub;
  if (typeof render !== 'function') return { render: builtInStub, name: 'built-in' };
  return { render: context => String(render(templateText, context)), name: 'acceptance-stubs.mjs' };
}
/** Stub files under the increment's stub folder that match no criterion: reported, never deleted. */
async function orphans(session: Session, incrementId: string, ids: readonly string[]): Promise<string[]> {
  const sample = acceptanceStubPath(session.ws.schema.acceptance, incrementId, 'AC-1'), folder = sample.slice(0, sample.lastIndexOf('/') + 1);
  const files = (await session.ws.files()).filter(path => path.startsWith(folder) && !path.slice(folder.length).includes('/'));
  return files.filter(path => { const match = /^ac-(\d+)\b/i.exec(path.slice(folder.length)); return match !== null && !ids.includes(`AC-${Number(match[1])}`); });
}
/** Plans the stubs and default evidence of every written criterion of the Increment. */
export async function planStubs(session: Session, incrementId: string): Promise<StubReport> {
  const path = session.ws.path('increment', incrementId);
  let text = (await session.text(path))!;
  const criteria = parseIncrement(text).acceptance.filter(item => !hasPlaceholder(item.text));
  const { render, name } = await renderer(session), report: StubReport = { renderer: name, created: [], existing: [], orphans: [] };
  for (const criterion of criteria) {
    const stub = acceptanceStubPath(session.ws.schema.acceptance, incrementId, criterion.id);
    if (!criterion.evidence.length) text = editIncrement(text, { kind: 'ac-set', id: criterion.id, evidence: [stub] }, { schema: session.ws.schema }).text;
    if (await session.text(stub) !== null) { report.existing.push(stub); continue; }
    session.write(stub, render({ incrementId, incrementPath: path, criterion: { id: criterion.id, text: criterion.text.replace(/\s*Evidence:.*$/s, '') } }));
    report.created.push(stub);
  }
  session.write(path, text);
  report.orphans = await orphans(session, incrementId, parseIncrement(text).acceptance.map(item => item.id));
  for (const orphan of report.orphans) session.warn('ACCEPTANCE_STUB_ORPHAN', `${orphan} matches no acceptance criterion; rename or delete it.`);
  return report;
}
