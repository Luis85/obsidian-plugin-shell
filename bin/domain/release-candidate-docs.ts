import { collectionBlock, collectionTableText } from './collection-register.ts';
import { candidateStatus, type CandidateRecord } from './release-candidate.ts';
/** One included release item as the candidate documents show it; `href` is relative to the candidate README. */
export interface CandidateIncrementView {
  id: string; title: string; status: string; kind: string; kindLabel: string; summary: string; sources: string[]; acceptance: string[]; risks: string[]; href: string;
}
/** A risk linked from the candidate's release items; `found` is false when no risk note has the id. */
export interface CandidateRiskView { id: string; found: boolean; title: string; status: string; level: string; levelLabel: string; open: boolean; href: string; from: string[] }
export interface CandidateDocsInput {
  record: CandidateRecord; increments: readonly CandidateIncrementView[]; missing: readonly string[]; risks: readonly CandidateRiskView[];
  asOf: string; riskFolder: string; errors: number;
}
/** The generated blocks of a candidate README, in document order. Everything outside them is authored text. */
export const candidateBlockNames: readonly string[] = ['candidate-items', 'candidate-risks', 'candidate-checklist', 'candidate-changelog'];
const cell = (value: string) => collectionTableText(value);
const link = (id: string, href: string) => href ? `[${id}](<${href.replace(/[<>]/g, '')}>)` : id;
const label = (status: string) => candidateStatus(status)?.label ?? status;
function statusLine(input: CandidateDocsInput): string {
  const { record } = input;
  const parts = [`**Status:** ${label(record.status)}`, `**Target date:** ${record.targetDate ?? '—'}`, `**Owner:** ${record.owner ? cell(record.owner) : '—'}`,
    `**Frozen:** ${record.frozen ?? '—'}`, `**Released:** ${record.released ?? '—'}`, `**Release items:** ${record.items.length}`];
  return parts.join(' · ');
}
function incrementsBlock(input: CandidateDocsInput): string {
  const { record, increments, missing } = input;
  const lines = [`_Generated by \`node bin/app candidate docs --version ${record.version}\` for ${input.asOf} from ${increments.length} release item note(s). Change release items and status with \`candidate\` commands; text outside the markers is yours._`,
    '', statusLine(input), ''];
  if (!increments.length) lines.push('_No release items yet. Add ready release items with `node bin/app candidate add --version ' + record.version + ' --item ITEM-0001`._');
  else {
    lines.push('| ID | Title | Kind | Status | Summary | Sources | Acceptance |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const item of increments) lines.push(`| ${link(item.id, item.href)} | ${cell(item.title)} | ${cell(item.kindLabel)} | ${cell(item.status)} | ${cell(item.summary)} | ${cell(item.sources.join(', '))} | ${cell(item.acceptance.join('; '))} |`);
  }
  if (missing.length) lines.push('', '### Not found', '', ...missing.map(id => `- ${id} (run \`node bin/app candidate check\`)`));
  return lines.join('\n') + '\n';
}
function risksBlock(input: CandidateDocsInput): string {
  if (!input.risks.length) return '_No linked risks. Release items link risks with their `risks` field (RISK ids)._\n';
  const lines = ['| Risk | Title | Status | Level | Linked from |', '| --- | --- | --- | --- | --- |'];
  for (const risk of input.risks) {
    const title = risk.found ? cell(risk.title) : `_not found in ${cell(input.riskFolder)}_`;
    lines.push(`| ${link(risk.id, risk.href)} | ${title} | ${cell(risk.status)} | ${cell(risk.levelLabel)} | ${risk.from.join(', ')} |`);
  }
  const open = input.risks.filter(risk => risk.open && ['high', 'critical'].includes(risk.level));
  lines.push('', open.length ? `**Open high or critical risks:** ${open.map(risk => risk.id).join(', ')}` : '_No linked risk is open at high or critical level._');
  return lines.join('\n') + '\n';
}
const reached = (record: CandidateRecord, statuses: readonly string[]) => statuses.includes(record.status);
function checklistBlock(input: CandidateDocsInput): string {
  const { record, increments } = input;
  const risky = input.risks.some(risk => !risk.found || (risk.open && ['high', 'critical'].includes(risk.level)));
  const items: Array<[boolean, string]> = [
    [record.items.length > 0, 'At least one release item is included'],
    [!input.missing.length, 'Every included release item note exists and is valid'],
    [increments.length > 0 && increments.every(item => item.acceptance.length > 0), 'Every release item has acceptance criteria'],
    [increments.length > 0 && increments.every(item => item.sources.length > 0), 'Every release item names its sources (prototype, design, brainstorm, PRD, risk or learning)'],
    [!risky, 'No linked risk is missing or open at high or critical level'],
    [input.errors === 0, '`node bin/app candidate check --json` reports no errors for this candidate'],
    [reached(record, ['frozen', 'qualified', 'released']), 'Frozen: the release item list is final (`candidate status --to frozen`)'],
    [reached(record, ['qualified', 'released']), 'Qualified: the release-approval process approved it (`node bin/app process run --name release-approval`), then `candidate status --to qualified`'],
    [reached(record, ['released']), 'Released: a maintainer cut and published the repository release separately (`npm run release:cut`, `npm run release:publish`); candidate commands never run them'],
  ];
  return items.map(([done, text]) => `- [${done ? 'x' : ' '}] ${text}`).join('\n') + '\n';
}
/** Keep a Changelog headings by release item kind; unknown project kinds are changes. */
const changelogHeading = (kind: string) => kind === 'feature' ? 'Added' : kind === 'fix' ? 'Fixed' : 'Changed';
const fenceSafe = (value: string) => value.replace(/\s+/g, ' ').replace(/`{3,}/g, '``').trim();
function changelogBlock(input: CandidateDocsInput): string {
  const { record } = input, lines = [`## [${record.version}] - ${record.released ?? record.targetDate ?? 'YYYY-MM-DD'}`];
  for (const heading of ['Added', 'Changed', 'Fixed']) {
    const entries = input.increments.filter(item => changelogHeading(item.kind) === heading);
    if (entries.length) lines.push('', `### ${heading}`, '', ...entries.map(item => `- ${fenceSafe(item.title)}: ${fenceSafe(item.summary)} (${item.id}, ${fenceSafe(item.kindLabel)})`));
  }
  if (lines.length === 1) lines.push('', '_No release items yet._');
  return ['_A draft entry in [Keep a Changelog](https://keepachangelog.com/en/1.1.0/) format. Copy it into the repository CHANGELOG.md by hand when the release is cut; nothing edits CHANGELOG.md automatically._',
    '', '````markdown', ...lines, '````'].join('\n') + '\n';
}
/** The inner text of every generated block; deterministic for one reference date. */
export function candidateDocs(input: CandidateDocsInput): Record<string, string> {
  const [increments, risks, checklist, changelog] = candidateBlockNames;
  return { [increments!]: incrementsBlock(input), [risks!]: risksBlock(input), [checklist!]: checklistBlock(input), [changelog!]: changelogBlock(input) };
}
/** The body of a new candidate README: authored headings and sections around freshly stamped generated blocks. */
export function candidateReadmeBody(version: string, goal: string | undefined, blocks: Record<string, string>, digest: (text: string) => string): string {
  const block = (name: string) => collectionBlock(name, blocks[name]!, digest);
  const [increments, risks, checklist, changelog] = candidateBlockNames.map(block);
  return [`# Release candidate ${version}\n`, '## Goal\n', `${goal ?? '_Describe what this release is for and who it serves._'}\n`, '## Release items\n', increments,
    '## Risks\n', risks, '## Release checklist\n', checklist, '## Changelog draft\n', changelog,
    '## Notes\n', '_Hand-written notes, decisions and links. `node bin/app candidate docs` only replaces the generated blocks; text outside their markers is kept byte for byte._\n'].join('\n');
}
