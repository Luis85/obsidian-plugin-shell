import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {APP,VERSION,UI_VERSION} from '../app.config.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFile(path.join(root,p),'utf8');
const shell=await read('dist/shell/index.html');
const scriptFile=shell.match(/<script\b[^>]*src="([^"]+)"[^>]*><\/script>/)?.[1];
const cssFiles=[...shell.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g)].map(m=>m[1]);
if(!scriptFile||!cssFiles.length)throw new Error('The Vite build is missing its script or stylesheet.');
const js=await read('dist/shell/'+scriptFile.replace(/^\.\//,''));
const css=(await Promise.all(cssFiles.map(p=>read('dist/shell/'+p.replace(/^\.\//,''))))).join('\n');
const bridge=await read('src/editor-bridge.js'),editorTheme=await read('src/editor-theme.css');
let notices='';try{notices=await read('dist/shell/THIRD-PARTY-NOTICES.txt');}catch{}
await fs.mkdir(path.join(root,'dist'),{recursive:true});
const {appId,file,title}=APP;
let editor=await read('editors/'+file);
editor=editor.replace(/<html([^>]*)>/,(_,attrs)=>'<html'+attrs.replace(/\sclass="[^"]*"/,'')+' class="family-editor">');
editor=editor.replace('</head>',()=>'<style id="family-editor-theme">'+editorTheme+'</style></head>');
editor=editor.replace('</body>',()=>'<script>'+bridge.replace(/<\/script/gi,'<\\/script')+'</script></body>');
let html=shell.replace(/<script\b[^>]*src="[^"]+"[^>]*><\/script>/,'');
html=html.replace(/<link\b[^>]*rel="stylesheet"[^>]*>/g,'');
html=html.replace(/<link\b[^>]*rel="modulepreload"[^>]*>/g,'');
html=html.replace(/<title>.*?<\/title>/,'<title>'+title+' · Obsidian Product Family</title>');
html=html.replace(/(<script type="application\/json" id="family-config">)[\s\S]*?(<\/script>)/,(_,a,b)=>a+JSON.stringify({appId,file,version:VERSION,uiVersion:UI_VERSION})+b);
html=html.replace('__FAMILY_EDITOR_BASE64__',Buffer.from(editor).toString('base64'));
html=html.replace('</head>',()=>'<style>'+css+'</style></head>');
html=html.replace('</body>',()=>'<script type="text/plain" id="family-third-party-notices">'+notices.replace(/<\/script/gi,'<\\/script')+'</script><script type="module">'+js.replace(/<\/script/gi,'<\\/script')+'</script></body>');
await fs.writeFile(path.join(root,'dist',file),html);
console.log(file+': '+Math.round(Buffer.byteLength(html)/1024)+' KB (self-contained)');
